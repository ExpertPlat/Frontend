/** Builds a concrete URL from a route pattern, e.g. withParams(PATHS.USER_CASE_DETAIL, { caseId: 1287 }). */
export function withParams(pattern, params = {}) {
  return pattern.replace(/:([A-Za-z]+)/g, (_, key) => encodeURIComponent(params[key] ?? ''));
}
